/// An original 5×7 pixel font (with one descender row) drawn in the spirit of
/// early-80s home-computer character ROMs. Each glyph sits in a 7×8 cell,
/// the Apple II text-mode geometry: 40 columns × 7 px = 280 px wide.
enum PixelFont {
    static let cellWidth = 7
    static let cellHeight = 8

    /// glyphs[c] = 8 rows; bit 4 is the leftmost of the 5 glyph pixels.
    static let glyphs: [Character: [UInt8]] = {
        var table: [Character: [UInt8]] = [:]
        for (char, art) in source {
            let rows = art.split(separator: "|", omittingEmptySubsequences: false)
            var bits = [UInt8](repeating: 0, count: cellHeight)
            for (r, row) in rows.prefix(cellHeight).enumerated() {
                var value: UInt8 = 0
                for (c, ch) in row.prefix(5).enumerated() where ch == "#" {
                    value |= 1 << UInt8(4 - c)
                }
                bits[r] = value
            }
            table[char] = bits
        }
        return table
    }()

    static func glyph(for char: Character) -> [UInt8] {
        glyphs[char] ?? glyphs["?"]!
    }

